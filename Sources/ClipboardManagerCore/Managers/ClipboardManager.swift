import Foundation
import SwiftUI
import AppKit
import UserNotifications

// MARK: - Custom Popup Window & Auto-Dismiss Delegate
public final class ClipboardWindow: NSWindow {
    public override var canBecomeKey: Bool { true }
    public override var canBecomeMain: Bool { true }
    public override var acceptsFirstResponder: Bool { true }
}

private final class PopupWindowDelegate: NSObject, NSWindowDelegate {
    weak var manager: ClipboardManager?

    func windowDidResignKey(_ notification: Notification) {
        guard NSApp.modalWindow == nil else { return }
        DispatchQueue.main.async { [weak self] in
            guard let manager = self?.manager, manager.isWindowVisible else { return }
            manager.hideWindow()
        }
    }
}

// MARK: - Clipboard Manager
public final class ClipboardManager: ObservableObject {
    public static let shared = ClipboardManager()

    /// Standard macOS pasteboard markers used by password managers & transient tools.
    public static let concealedPasteboardTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
        NSPasteboard.PasteboardType("com.typeit4me.clipping")
    ]

    @Published public var items: [ClipboardItem] = []
    @Published public var isWindowVisible = false
    @Published public var selectedPreviewItem: ClipboardItem?
    @Published public var isPaused = false
    @Published public var pauseUntil: Date?

    @Published public var iCloudSync: iCloudSyncManager!
    @Published public var scheduledClear: ScheduledClearManager!
    @Published public var integrations: IntegrationManager!
    @Published public var screenshotWatcher: ScreenshotWatcher!

    public private(set) weak var previousFrontmostApp: NSRunningApplication?

    private let settings: AppSettings
    private let imageStorage: ImageStorageManager
    private let historyFileURL: URL
    private let legacyDefaults: UserDefaults
    private let enableRuntimeSideEffects: Bool
    private let persistenceQueue = DispatchQueue(label: "com.clipboardmanager.persistence", qos: .utility)

    private var timer: Timer?
    private var pauseTimer: Timer?
    private var lastChangeCount: Int = 0
    private var clipboardWindow: ClipboardWindow?
    private let windowDelegate = PopupWindowDelegate()

    public init(
        settings: AppSettings = .shared,
        imageStorage: ImageStorageManager = .shared,
        historyFileURL: URL? = nil,
        legacyDefaults: UserDefaults = .standard,
        enableRuntimeSideEffects: Bool = true
    ) {
        self.settings = settings
        self.imageStorage = imageStorage
        self.historyFileURL = historyFileURL ?? AppInfo.appSupportDirectory.appendingPathComponent("history.json")
        self.legacyDefaults = legacyDefaults
        self.enableRuntimeSideEffects = enableRuntimeSideEffects

        self.iCloudSync = iCloudSyncManager()
        self.integrations = IntegrationManager(defaults: legacyDefaults)
        self.screenshotWatcher = ScreenshotWatcher()
        self.scheduledClear = ScheduledClearManager(clipboardManager: self, defaults: legacyDefaults)
        self.windowDelegate.manager = self

        loadItems()

        if enableRuntimeSideEffects {
            let validImages = Set(items.compactMap(\.imageFileName))
            persistenceQueue.async { [imageStorage] in
                imageStorage.cleanupOrphanedImages(keeping: validImages)
            }
            updateScreenshotWatching()
            startMonitoring()
        }
    }

    // MARK: - Monitoring & Pause Mode

    public func startMonitoring() {
        timer?.invalidate()
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: settings.updateInterval, repeats: true) { [weak self] _ in
            self?.checkClipboard()
        }
    }

    public func restartMonitoring() {
        guard enableRuntimeSideEffects else { return }
        startMonitoring()
    }

    public func pauseMonitoring(for duration: TimeInterval? = nil) {
        pauseTimer?.invalidate()
        pauseTimer = nil
        isPaused = true

        if let duration, duration > 0 {
            let resumeDate = Date().addingTimeInterval(duration)
            pauseUntil = resumeDate
            pauseTimer = Timer.scheduledTimer(withTimeInterval: duration, repeats: false) { [weak self] _ in
                self?.resumeMonitoring()
            }
        } else {
            pauseUntil = nil
        }
    }

    public func resumeMonitoring() {
        pauseTimer?.invalidate()
        pauseTimer = nil
        isPaused = false
        pauseUntil = nil
        // Sync changeCount so anything copied while paused is not retroactively captured.
        lastChangeCount = NSPasteboard.general.changeCount
    }

    public func updateScreenshotWatching() {
        guard enableRuntimeSideEffects else { return }
        if settings.watchScreenshots {
            screenshotWatcher?.startWatching()
        } else {
            screenshotWatcher?.stopWatching()
        }
    }

    public func recordPasteboardChange() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    // MARK: - Security Filtering (Testable)

    public func shouldIgnorePasteboard(
        types: [NSPasteboard.PasteboardType],
        frontmostBundleID: String?
    ) -> Bool {
        if isPaused {
            return true
        }

        if settings.ignoreConcealedPasteboard {
            if !Self.concealedPasteboardTypes.isDisjoint(with: types) {
                return true
            }
        }

        if settings.isPasswordManagerExclusionEnabled, let bundleID = frontmostBundleID {
            if settings.ignoredBundleIDs.contains(bundleID) {
                return true
            }
        }

        return false
    }

    private func checkClipboard() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let frontApp = NSWorkspace.shared.frontmostApplication
        let types = pasteboard.types ?? []

        if shouldIgnorePasteboard(types: types, frontmostBundleID: frontApp?.bundleIdentifier) {
            return
        }

        let sourceBundleID = frontApp?.bundleIdentifier
        let sourceName = frontApp?.localizedName

        if let imageData = extractImageData(from: pasteboard) {
            addImageItem(imageData: imageData, sourceAppBundleID: sourceBundleID, sourceAppName: sourceName)
        } else if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            if SmartDetector.isValidURL(string) {
                addURLItem(url: string, sourceAppBundleID: sourceBundleID, sourceAppName: sourceName)
            } else {
                addTextItem(content: string, sourceAppBundleID: sourceBundleID, sourceAppName: sourceName)
            }
        }
    }

    private func extractImageData(from pasteboard: NSPasteboard) -> Data? {
        if let pngData = pasteboard.data(forType: .png) {
            return pngData
        }
        if let tiffData = pasteboard.data(forType: .tiff) {
            return tiffData
        }

        if pasteboard.canReadObject(forClasses: [NSImage.self], options: nil),
           let image = NSImage(pasteboard: pasteboard),
           let tiffData = image.tiffRepresentation {
            return tiffData
        }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL] {
            let imageExts: Set<String> = ["png", "jpg", "jpeg", "heic", "webp", "tiff", "bmp"]
            for url in urls where imageExts.contains(url.pathExtension.lowercased()) {
                if let data = try? Data(contentsOf: url) {
                    return data
                }
            }
        }

        return nil
    }

    // MARK: - Item Mutations

    public func addTextItem(
        content: String,
        sourceAppBundleID: String? = nil,
        sourceAppName: String? = nil
    ) {
        let trimmedContent = content.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmedContent.isEmpty else { return }

        let existingPin = items.first(where: { $0.content == trimmedContent && $0.type == .text })?.isPinned ?? false
        items.removeAll { $0.content == trimmedContent && $0.type == .text }

        let newItem = ClipboardItem(
            content: trimmedContent,
            isPinned: existingPin,
            sourceAppBundleID: sourceAppBundleID,
            sourceAppName: sourceAppName,
            detectEntities: settings.enableSmartDetection
        )
        items.insert(newItem, at: 0)

        finalizeMutation(addedItem: newItem)
    }

    public func addImageItem(
        imageData: Data,
        sourceAppBundleID: String? = nil,
        sourceAppName: String? = nil
    ) {
        guard let saved = imageStorage.saveImageWithMetadata(imageData) else { return }

        let newItem = ClipboardItem(
            imageFileName: saved.fileName,
            sourceAppBundleID: sourceAppBundleID,
            sourceAppName: sourceAppName,
            imageWidth: saved.width,
            imageHeight: saved.height,
            imageByteCount: saved.byteCount
        )
        items.insert(newItem, at: 0)

        let itemId = newItem.id
        if enableRuntimeSideEffects && settings.isOCREnabled {
            OCRManager.shared.recognizeText(from: imageData) { [weak self] recognizedText in
                guard let self, let text = recognizedText else { return }
                if let index = self.items.firstIndex(where: { $0.id == itemId }) {
                    self.items[index].ocrText = text
                    self.saveItems()
                }
            }
        }

        finalizeMutation(addedItem: newItem)
    }

    public func addScreenshotItem(_ imageData: Data) {
        guard !isPaused else { return }
        addImageItem(imageData: imageData, sourceAppBundleID: "com.apple.screencapture", sourceAppName: "Screenshot")

        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setData(imageData, forType: .png)
        if let nsImage = NSImage(data: imageData), let tiff = nsImage.tiffRepresentation {
            pasteboard.setData(tiff, forType: .tiff)
        }
        lastChangeCount = pasteboard.changeCount
    }

    public func addURLItem(
        url: String,
        sourceAppBundleID: String? = nil,
        sourceAppName: String? = nil
    ) {
        let trimmedURL = url.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmedURL.isEmpty else { return }

        let existingPin = items.first(where: { $0.content == trimmedURL && $0.type == .url })?.isPinned ?? false
        items.removeAll { $0.content == trimmedURL && $0.type == .url }

        let newItem = ClipboardItem(
            url: trimmedURL,
            isPinned: existingPin,
            sourceAppBundleID: sourceAppBundleID,
            sourceAppName: sourceAppName
        )
        items.insert(newItem, at: 0)

        finalizeMutation(addedItem: newItem)
    }

    public func addItem(content: String) {
        if SmartDetector.isValidURL(content) {
            addURLItem(url: content)
        } else {
            addTextItem(content: content)
        }
    }

    private func finalizeMutation(addedItem: ClipboardItem) {
        sortItems()
        enforceMaxItems()
        saveItems()

        if enableRuntimeSideEffects {
            showSmartNotification(for: addedItem)
            iCloudSync?.syncClipboardItem(addedItem)
        }
    }

    /// Trims unpinned items first so pinned items are never evicted while within limit, and deletes evicted images.
    public func enforceMaxItems() {
        let limit = max(settings.maxItems, 1)
        guard items.count > limit else { return }

        let pinned = items.filter(\.isPinned)
        let unpinned = items.filter { !$0.isPinned }

        let remainingSlots = max(0, limit - pinned.count)
        let keptUnpinned = Array(unpinned.prefix(remainingSlots))
        let evictedUnpinned = Array(unpinned.dropFirst(remainingSlots))

        var evicted = evictedUnpinned
        let keptPinned: [ClipboardItem]
        if pinned.count > limit {
            keptPinned = Array(pinned.prefix(limit))
            evicted.append(contentsOf: pinned.dropFirst(limit))
        } else {
            keptPinned = pinned
        }

        for item in evicted {
            if let fileName = item.imageFileName {
                imageStorage.deleteImage(fileName: fileName)
            }
        }

        items = keptPinned + keptUnpinned
    }

    public func clearUnpinnedItems() {
        let removed = items.filter { !$0.isPinned }
        for item in removed {
            if let fileName = item.imageFileName {
                imageStorage.deleteImage(fileName: fileName)
            }
        }
        items.removeAll { !$0.isPinned }
        if let preview = selectedPreviewItem, !preview.isPinned {
            selectedPreviewItem = nil
        }
        saveItems()
    }

    public func deleteAllItems(includePinned: Bool = true) {
        if !includePinned {
            clearUnpinnedItems()
            return
        }
        for item in items {
            if let fileName = item.imageFileName {
                imageStorage.deleteImage(fileName: fileName)
            }
        }
        items.removeAll()
        selectedPreviewItem = nil
        saveItems()
    }

    @discardableResult
    public func removeItems(olderThan cutoffDate: Date, preservePinned: Bool) -> Int {
        let toRemove = items.filter { item in
            let isOld = item.timestamp < cutoffDate
            return preservePinned ? (!item.isPinned && isOld) : isOld
        }
        guard !toRemove.isEmpty else { return 0 }

        let removeIDs = Set(toRemove.map(\.id))
        for item in toRemove {
            if let fileName = item.imageFileName {
                imageStorage.deleteImage(fileName: fileName)
            }
        }
        items.removeAll { removeIDs.contains($0.id) }
        if let preview = selectedPreviewItem, removeIDs.contains(preview.id) {
            selectedPreviewItem = nil
        }
        saveItems()
        return toRemove.count
    }

    public func togglePin(for item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        sortItems()
        saveItems()
    }

    public func removeItem(_ item: ClipboardItem) {
        if let fileName = item.imageFileName {
            imageStorage.deleteImage(fileName: fileName)
        }
        items.removeAll { $0.id == item.id }
        if selectedPreviewItem?.id == item.id {
            selectedPreviewItem = nil
        }
        saveItems()
    }

    private func sortItems() {
        let pinned = items.filter(\.isPinned)
        let unpinned = items.filter { !$0.isPinned }
        items = pinned + unpinned
    }

    // MARK: - Pasteboard Write Helpers

    public func copyToClipboard(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        switch item.type {
        case .text, .url:
            pasteboard.setString(item.content, forType: .string)
        case .image:
            if let fileName = item.imageFileName, let imageData = imageStorage.loadImageData(fileName: fileName) {
                pasteboard.setData(imageData, forType: .png)
                if let image = NSImage(data: imageData), let tiff = image.tiffRepresentation {
                    pasteboard.setData(tiff, forType: .tiff)
                }
            }
        }

        lastChangeCount = pasteboard.changeCount
    }

    public func copyPlainTextToClipboard(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    // MARK: - Persistence (Atomic JSON file + UserDefaults Migration)

    public func saveItems() {
        let snapshot = items
        let targetURL = historyFileURL

        let writeBlock = {
            do {
                let directory = targetURL.deletingLastPathComponent()
                try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
                let data = try JSONEncoder().encode(snapshot)
                try data.write(to: targetURL, options: .atomic)
            } catch {
                print("Error saving clipboard history: \(error)")
            }
        }

        if enableRuntimeSideEffects {
            persistenceQueue.async(execute: writeBlock)
        } else {
            writeBlock()
        }
    }

    private func loadItems() {
        // 1. Primary JSON file storage in Application Support
        if let data = try? Data(contentsOf: historyFileURL),
           let decoded = try? JSONDecoder().decode([ClipboardItem].self, from: data) {
            items = decoded
            sortItems()
            return
        }

        // 2. One-time migration from legacy UserDefaults storage
        if let legacyData = legacyDefaults.data(forKey: "ClipboardItems"),
           let decoded = try? JSONDecoder().decode([ClipboardItem].self, from: legacyData) {
            items = decoded
            sortItems()
            saveItems()
            legacyDefaults.removeObject(forKey: "ClipboardItems")
        }
    }

    public func mergeRemoteItems(_ remoteItems: [ClipboardItem]) {
        var merged = items
        let existingIDs = Set(merged.map(\.id))

        for remote in remoteItems where !existingIDs.contains(remote.id) {
            merged.append(remote)
        }

        merged.sort { lhs, rhs in
            if lhs.isPinned != rhs.isPinned { return lhs.isPinned }
            return lhs.timestamp > rhs.timestamp
        }

        items = merged
        enforceMaxItems()
        saveItems()
    }

    // MARK: - Floating Popup Window

    public func toggleWindow() {
        DispatchQueue.main.async { [weak self] in
            guard let self else { return }
            self.isWindowVisible ? self.hideWindow() : self.showWindow()
        }
    }

    public func showWindow() {
        // Capture currently focused external app before activating ClipboardManager.
        if let frontApp = NSWorkspace.shared.frontmostApplication,
           frontApp.bundleIdentifier != Bundle.main.bundleIdentifier {
            previousFrontmostApp = frontApp
        }

        let windowSize = settings.compactMode
            ? CGSize(width: 400, height: 430)
            : CGSize(width: 460, height: 520)

        if clipboardWindow == nil {
            let contentView = ClipboardPopupView()
                .environmentObject(self)
                .environmentObject(settings)

            let customWindow = ClipboardWindow(
                contentRect: NSRect(origin: .zero, size: windowSize),
                styleMask: [.borderless],
                backing: .buffered,
                defer: false
            )
            customWindow.delegate = windowDelegate
            customWindow.contentView = NSHostingView(rootView: contentView)
            customWindow.backgroundColor = .clear
            customWindow.isOpaque = false
            customWindow.hasShadow = true
            customWindow.level = .floating
            customWindow.isMovableByWindowBackground = false
            customWindow.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient]
            customWindow.acceptsMouseMovedEvents = true
            customWindow.isReleasedWhenClosed = false
            customWindow.contentView?.wantsLayer = true

            clipboardWindow = customWindow
        }

        if let window = clipboardWindow {
            positionWindow(window, size: windowSize)
            window.makeKeyAndOrderFront(nil)
            NSApp.activate(ignoringOtherApps: true)
            window.orderFrontRegardless()
        }

        isWindowVisible = true
    }

    public func hideWindow() {
        selectedPreviewItem = nil
        clipboardWindow?.orderOut(nil)
        isWindowVisible = false
    }

    private func positionWindow(_ window: NSWindow, size: CGSize) {
        let mouseLocation = NSEvent.mouseLocation
        let activeScreen = NSScreen.screens.first(where: { NSMouseInRect(mouseLocation, $0.frame, false) })
            ?? NSScreen.main
            ?? NSScreen.screens.first

        guard let visibleFrame = activeScreen?.visibleFrame else {
            window.setContentSize(size)
            window.center()
            return
        }

        let margin: CGFloat = 12
        var origin: CGPoint

        if settings.openNearCursor {
            origin = CGPoint(
                x: mouseLocation.x - size.width / 2,
                y: mouseLocation.y - size.height + 24
            )
        } else {
            origin = CGPoint(
                x: visibleFrame.midX - size.width / 2,
                y: visibleFrame.midY - size.height / 2
            )
        }

        origin.x = min(max(origin.x, visibleFrame.minX + margin), visibleFrame.maxX - size.width - margin)
        origin.y = min(max(origin.y, visibleFrame.minY + margin), visibleFrame.maxY - size.height - margin)

        window.setFrame(NSRect(origin: origin, size: size), display: true)
    }

    private func showSmartNotification(for item: ClipboardItem) {
        guard settings.showNotifications else { return }

        let content = UNMutableNotificationContent()
        switch item.type {
        case .text:
            content.title = "Text Copied"
            content.body = String(item.content.prefix(60)) + (item.content.count > 60 ? "…" : "")
        case .image:
            content.title = "Image Copied"
            content.body = "Image saved to clipboard history"
        case .url:
            content.title = "URL Copied"
            content.body = item.content
        }

        content.sound = nil
        UNUserNotificationCenter.current().add(
            UNNotificationRequest(identifier: UUID().uuidString, content: content, trigger: nil)
        )
    }
}
